async (page) => {
  const check = (value, message) => { if (!value) throw Error(message) };
  const origin = 'http://127.0.0.1:8765';
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text())});
  const projects=await(await page.request.get(origin+'/api/projects')).json();
  const project=projects.find(p=>p.metadata.filename==='moonbeam-2026-10-13-12h-75x-compact.mp4');
  check(project,'Prepared Moonbeam video is not registered');
  const demo=projects.find(p=>p.id==='cnrpark-day');
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(origin);
  await page.getByLabel('Исследование',{exact:true}).selectOption(project.id);
  await page.waitForFunction(()=>document.querySelector('video')?.readyState>=2);
  check(await page.getByLabel('Ускорение исходника',{exact:true}).inputValue()==='75','Known acceleration was not restored');
  check(await page.getByRole('button',{name:'Видео',exact:true}).getAttribute('aria-pressed')==='true','An unanalyzed source should open as color video');
  check(await page.getByRole('button',{name:'Тепловая карта',exact:true}).isDisabled(),'Heatmap must wait for real analysis');
  check((await page.locator('.observation-duration').innerText()).includes('12 ч'),'Source duration is not twelve hours');
  check(project.slots.length===0 && !project.completed_run_id,'New camera should not reuse Pisa geometry or results');
  const media=await page.locator('video').evaluate(v=>({duration:v.duration,width:v.videoWidth,height:v.videoHeight,error:v.error?.code||null}));
  check(Math.abs(media.duration-576)<.1 && media.width===1280 && media.height===720 && !media.error,'Prepared file is not playable with the expected dimensions and duration');
  await page.getByLabel('Позиция видео',{exact:true}).fill('144');
  await page.waitForFunction(()=>!document.querySelector('video').seeking);
  check(await page.locator('.playback-time').innerText()==='15:59','The player shows clip minutes instead of the source UTC clock');
  const ratio=await page.locator('video').evaluate(v=>{const r=v.getBoundingClientRect();return r.width/r.height});
  check(Math.abs(ratio-16/9)<.01,'The camera image is distorted');
  await page.getByRole('button',{name:'Воспроизвести',exact:true}).click();
  await page.getByRole('button',{name:'Пауза',exact:true}).click();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'artifacts/new-video-desktop.png',fullPage:true});
  await page.locator('.video-column').screenshot({path:'artifacts/new-video-player.png'});
  await page.getByLabel('Позиция видео',{exact:true}).fill('575');
  await page.waitForFunction(()=>!document.querySelector('video').seeking);
  check(await page.locator('video').evaluate(v=>v.currentTime>574&&!v.error),'End of the video cannot be decoded');
  check((await page.locator('.playback-time').innerText()).includes('(+1 д)'),'Crossing midnight is not indicated');
  await page.reload();
  await page.getByLabel('Ускорение исходника',{exact:true}).waitFor();
  check(await page.getByLabel('Ускорение исходника',{exact:true}).inputValue()==='75','Reload reset the prepared source scale');
  await page.getByLabel('Позиция видео',{exact:true}).fill('144');
  await page.waitForFunction(()=>!document.querySelector('video').seeking);
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'New source layout overflows on mobile');
  await page.screenshot({path:'artifacts/new-video-mobile.png',fullPage:true});
  const final=await(await page.request.get(origin+'/api/projects/cnrpark-day')).json();
  check(final.revision===demo.revision && final.latest_run.id===demo.latest_run.id,'Import changed the existing example');
  check(!errors.length,errors.join('; '));
  return {passed:true,projectId:project.id,media,renderedRatio:ratio,browserErrors:errors,sourceSeconds:project.metadata.source_duration_seconds,timeScale:75};
}
