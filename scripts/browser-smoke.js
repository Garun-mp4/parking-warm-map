async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message) }
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.setViewportSize({ width: 1440, height: 1080 })
  await page.goto('http://127.0.0.1:8765')
  await page.getByRole('heading', { name: 'День в цифрах' }).waitFor()
  check(await page.locator('video').getAttribute('poster') === '/api/projects/cnrpark-day/poster?first=true', 'Initial poster is not the first source capture')
  await page.getByRole('button', { name: 'Тепловая карта', exact: true }).click()
  check(await page.locator('.heat-scale').isVisible(), 'Heatmap legend is missing')
  await page.getByRole('button', { name: 'Занятость', exact: true }).click()
  await page.getByRole('button', { name: 'Воспроизвести', exact: true }).click()
  await page.getByRole('button', { name: 'Пауза', exact: true }).click()
  await page.locator('[data-cell="0-0"]').click()
  await page.keyboard.press('ArrowRight')
  check(await page.evaluate(() => document.activeElement?.getAttribute('data-cell')) === '0-1', 'Matrix arrow navigation failed')
  check(await page.locator('video').evaluate(video => Math.abs(video.currentTime - 2) < .1), 'Matrix did not seek the actual corresponding frame')
  await page.getByRole('button', { name: 'Развернуть видео' }).click()
  check(await page.evaluate(() => !!document.fullscreenElement), 'Fullscreen did not open')
  const alignment = await page.evaluate(() => {
    const video = document.querySelector('video').getBoundingClientRect()
    const overlay = document.querySelector('.parking-overlay').getBoundingClientRect()
    return { dx: Math.abs(video.x - overlay.x), dy: Math.abs(video.y - overlay.y), dw: Math.abs(video.width - overlay.width), ratio: video.width / video.height }
  })
  check(alignment.dx < 1 && alignment.dy < 1 && alignment.dw < 1 && Math.abs(alignment.ratio - 4 / 3) < .01, 'Fullscreen overlay is misaligned')
  await page.getByRole('button', { name: 'Свернуть видео' }).click()
  await page.waitForFunction(() => !document.fullscreenElement)
  await page.getByLabel('Поиск места').fill('613')
  await page.waitForFunction(() => document.querySelectorAll('tbody tr').length === 1)
  await page.getByLabel('Поиск места').fill('')
  await page.getByLabel('Начало интервала').fill('3600')
  await page.getByRole('button', { name: 'Весь день', exact: true }).click()
  for (const [button, extension] of [['CSV', 'csv'], ['Карта PNG', 'png'], ['Видео MP4', 'mp4']]) {
    const [download] = await Promise.all([page.waitForEvent('download', { timeout: 120000 }), page.getByRole('button', { name: button, exact: true }).click()])
    check(download.suggestedFilename().endsWith('.' + extension), 'Wrong export filename')
    await download.saveAs('artifacts/qa-export.' + extension)
  }
  await page.getByRole('button', { name: 'Разметка', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить', exact: true }).click()
  const box = await page.locator('.parking-overlay').boundingBox()
  check(!!box, 'Editor did not open')
  for (const [x,y] of [[.3,.47],[.4,.47],[.4,.55],[.3,.55]]) await page.mouse.click(box.x + box.width*x, box.y + box.height*y)
  await page.getByRole('button', { name: 'Замкнуть место', exact: true }).click()
  await page.getByLabel('Отменить изменение').click()
  await page.getByRole('button', { name: 'Сохранить разметку', exact: true }).click()
  await page.getByRole('button', { name: 'Изменения сохранены', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Обзор', exact: true }).click()
  await page.getByLabel('Модель', { exact: true }).selectOption('yolo11s')
  await page.getByRole('button', { name: 'Рассчитать карту', exact: true }).click()
  await page.getByRole('button', { name: 'Отменить', exact: true }).click()
  await page.getByRole('button', { name: 'Рассчитать карту', exact: true }).waitFor({ timeout: 120000 })
  const cancelled = await (await page.request.get('/api/projects/cnrpark-day')).json()
  check(cancelled.latest_run.status === 'cancelled', 'Cancellation was not persisted')
  await page.getByRole('button', { name: 'Новое видео', exact: true }).click()
  await page.getByLabel('Название', { exact: true }).fill('QA · проверка загрузки')
  await page.getByLabel('Видеофайл').setInputFiles('data/qa-upload.mp4')
  await page.getByRole('button', { name: 'Загрузить и разметить' }).click()
  await page.getByRole('heading', { name: /Каждому месту/ }).waitFor({ timeout: 120000 })
  await page.getByRole('button', { name: 'Добавить', exact: true }).click()
  const uploadedBox = await page.locator('.parking-overlay').boundingBox()
  for (const [x,y] of [[.2,.2],[.4,.2],[.4,.4],[.2,.4]]) await page.mouse.click(uploadedBox.x + uploadedBox.width*x, uploadedBox.y + uploadedBox.height*y)
  await page.getByRole('button', { name: 'Замкнуть место', exact: true }).click()
  await page.getByLabel('Название места', { exact: true }).fill('Проверочное место')
  await page.getByRole('button', { name: 'Сохранить разметку', exact: true }).click()
  await page.getByRole('button', { name: 'Изменения сохранены', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Обзор', exact: true }).click()
  await page.getByLabel('Ускорение исходника', { exact: true }).fill('60')
  await page.getByRole('button', { name: 'Рассчитать карту', exact: true }).click()
  await page.getByRole('heading', { name: 'День в цифрах' }).waitFor({ timeout: 120000 })
  check(await page.locator('.observation-duration').textContent() === '4 мин', 'Declared source time scale was not applied')
  const uploadedProjectId = await page.getByLabel('Исследование', { exact: true }).inputValue()
  await page.getByLabel('Исследование', { exact: true }).selectOption('cnrpark-day')
  await page.getByRole('heading', { name: 'День в цифрах' }).waitFor()
  await page.getByRole('button', { name: 'Методика', exact: true }).click()
  check(await page.getByText('07:22 до 17:34', { exact: false }).count() > 0, 'Source provenance is missing')
  await page.getByRole('button', { name: 'Обзор', exact: true }).click()
  await page.getByRole('button', { name: 'Тепловая карта', exact: true }).click()
  await page.evaluate(() => window.scrollTo(0,0))
  await page.screenshot({ path: 'artifacts/final-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'artifacts/final-mobile.png', fullPage: true })
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile page overflows horizontally')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  check(await page.evaluate(() => matchMedia('(prefers-reduced-motion: reduce)').matches), 'Reduced motion emulation failed')
  check(errors.length === 0, 'Browser errors: ' + errors.join('; '))
  return { passed: true, uploadedProjectId, scenarios: ['real analysis', 'play/pause', 'source timestamps', 'keyboard matrix', 'fullscreen alignment', 'filter', 'time range', 'CSV/PNG/MP4 exports', 'polygon add/undo/save', 'cancel', 'real upload', '60x time scale', 'source methodology', 'mobile', 'reduced motion'], browserErrors: errors }
}
