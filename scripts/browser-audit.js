async (page) => {
  const check = (value, message) => { if (!value) throw new Error(message) };
  const origin = 'http://127.0.0.1:8765';
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(origin);
  await page.locator('.heatmap-layer[data-ready="true"]').waitFor();
  const original = await (await page.request.get(origin+'/api/projects/cnrpark-day')).json();
  const originalResult = await (await page.request.get(origin+'/api/runs/'+original.completed_run_id+'/result')).json();
  check(await page.getByRole('button',{name:'Обзор',exact:true}).getAttribute('aria-current') === 'page', 'Current section is not announced');
  check(await page.getByRole('button',{name:'Тепловая карта',exact:true}).getAttribute('aria-pressed') === 'true', 'Current layer is not announced');
  const placement = await page.evaluate(() => {
    const period = document.querySelector('.map-range').getBoundingClientRect();
    const map = document.querySelector('.video-stage').getBoundingClientRect();
    return {periodY:period.top+scrollY,mapY:map.top+scrollY,gap:period.top-map.bottom};
  });
  check(placement.gap >= 0 && placement.gap < 240, 'Period controls are far from the map');
  await page.getByRole('button',{name:'Разметка',exact:true}).click();
  await page.locator('.slot-group').first().click();
  const name = page.getByLabel('Название места',{exact:true});
  const savedName = await name.inputValue();
  await name.fill(savedName+' QA');
  check(await page.evaluate(()=>!dispatchEvent(new Event('beforeunload',{cancelable:true}))), 'Dirty edits are not protected on reload');
  await page.getByRole('button',{name:'Обзор',exact:true}).click();
  check(await page.locator('.draft-notice').isVisible(), 'Retained draft is not discoverable');
  await page.getByRole('button',{name:'Вернуться к разметке',exact:false}).click();
  check(await name.inputValue() === savedName+' QA', 'Section navigation lost the draft');
  await page.getByLabel('Отменить изменение').click();
  check(await name.inputValue() === savedName, 'Undo did not restore the saved name');
  check(await page.getByRole('button',{name:'Изменения сохранены',exact:true}).isDisabled(), 'Undo still leaves a false dirty flag');
  check(await page.evaluate(()=>dispatchEvent(new Event('beforeunload',{cancelable:true}))), 'Clean layout incorrectly blocks reload');
  await page.getByRole('button',{name:'Обзор',exact:true}).click();

  let releaseSummary;
  let summaryRequested;
  const summaryGate = new Promise(resolve=>{releaseSummary=resolve});
  const summarySeen = new Promise(resolve=>{summaryRequested=resolve});
  await page.route('**/api/runs/*/summary?**',async route=>{
    const response=await route.fetch();
    summaryRequested();
    await summaryGate;
    await route.fulfill({response});
  },{times:1});
  await page.getByLabel('Конец интервала',{exact:true}).fill('9180');
  await summarySeen;
  check(!await page.locator('.summary-strip').isVisible(), 'Old statistics are visible under the new interval');
  check(await page.locator('.summary-status').isVisible(), 'Missing summary loading feedback');
  check(await page.getByRole('button',{name:'Карта PNG',exact:true}).isDisabled(), 'Export should wait for the current interval');
  check(await page.getByLabel('Конец интервала',{exact:true}).isVisible(), 'Period controls disappeared during loading');
  releaseSummary();
  await page.locator('.summary-strip').waitFor({state:'visible'});
  await page.unrouteAll({behavior:'wait'});
  await page.route('**/api/runs/*/summary?**',route=>route.fulfill({status:500,json:{detail:'Контрольная ошибка статистики'}}),{times:1});
  await page.getByLabel('Конец интервала',{exact:true}).fill('12000');
  await page.getByRole('button',{name:'Повторить загрузку статистики',exact:true}).waitFor();
  await page.getByRole('button',{name:'Повторить загрузку статистики',exact:true}).click();
  await page.locator('.summary-strip').waitFor({state:'visible'});
  await page.getByRole('button',{name:'Весь день',exact:true}).click();
  await page.locator('.heatmap-layer[data-ready="true"]').waitFor();
  await page.unrouteAll({behavior:'wait'});

  // Large-data and request-order fixtures exist only in this browser. Never write demo data.
  const longResult = {...originalResult,samples:Array.from({length:600},(_,i)=>({...originalResult.samples[i%originalResult.samples.length],video_seconds:i/600*42,source_seconds:i/600*originalResult.source_duration_seconds}))};
  let intercepted = 0;
  await page.route('**/api/runs/*/result',route=>{intercepted++;return route.fulfill({json:longResult})});
  await page.reload();
  await page.getByText('Наблюдения 1–24 из 600',{exact:true}).waitFor();
  check(intercepted > 0, 'Long-recording fixture was not actually loaded');
  const stressCells = await page.locator('.matrix-cell').count();
  check(stressCells === 54*24, 'The matrix rendered all 600 observations at once');
  await page.getByRole('button',{name:'Следующие наблюдения',exact:true}).click();
  await page.getByText('Наблюдения 25–48 из 600',{exact:true}).waitFor();
  await page.locator('[data-cell="0-24"]').click();
  await page.keyboard.press('ArrowLeft');
  await page.waitForFunction(()=>document.activeElement?.getAttribute('data-cell') === '0-23');
  check(await page.locator('video').evaluate(v=>Math.abs(v.currentTime-23/600*42)<.1), 'Cross-page keyboard navigation did not seek the frame');
  await page.getByRole('button',{name:'Следующие наблюдения',exact:true}).click();
  await page.getByRole('button',{name:'К текущему кадру',exact:true}).click();
  await page.getByText('Наблюдения 1–24 из 600',{exact:true}).waitFor();
  await page.unrouteAll({behavior:'wait'});

  const aliases = ['qa-slow','qa-fast'].map(id=>({...original,id,title:id,latest_run:{...original.latest_run,settings:{...original.latest_run.settings,model:'yolo11s',confidence:.35,time_scale:60}},completed_run_id:null,metadata:{...original.metadata,kind:'video'}}));
  let releaseSlow, slowRequested, slowFinished;
  const slowGate = new Promise(resolve=>{releaseSlow=resolve});
  const slowSeen = new Promise(resolve=>{slowRequested=resolve});
  const slowDone = new Promise(resolve=>{slowFinished=resolve});
  await page.route('**/api/projects',route=>route.fulfill({json:[original,...aliases]}));
  await page.route('**/api/projects/qa-*',async route=>{
    const fixture=aliases.find(p=>route.request().url().endsWith(p.id));
    if (!fixture) return route.continue();
    if (fixture.id==='qa-slow') {slowRequested();await slowGate;}
    await route.fulfill({json:fixture});
    if(fixture.id==='qa-slow') slowFinished();
  });
  await page.route('**/api/projects/qa-*/*',async route=>{
    const response=await route.fetch({url:route.request().url().replace(/qa-(slow|fast)/,'cnrpark-day')});
    await route.fulfill({response});
  });
  await page.reload();
  await page.getByLabel('Исследование',{exact:true}).selectOption('qa-slow');
  await slowSeen;
  await page.getByLabel('Исследование',{exact:true}).selectOption('qa-fast');
  await page.waitForFunction(()=>document.querySelector('#project').value==='qa-fast');
  releaseSlow();await slowDone;
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  check(await page.getByLabel('Исследование',{exact:true}).inputValue()==='qa-fast','Late response replaced the chosen project');
  check(await page.getByLabel('Модель',{exact:true}).inputValue()==='yolo11s','Saved model settings were reset');
  check(await page.getByLabel('Ускорение исходника',{exact:true}).inputValue()==='60','Saved speed scale was reset');
  await page.route('**/api/runs/*/result',route=>route.fulfill({status:404,json:{detail:'Контрольный отсутствующий файл результата'}}),{times:1});
  await page.getByLabel('Исследование',{exact:true}).selectOption('cnrpark-day');
  await page.getByText('Контрольный отсутствующий файл результата',{exact:true}).waitFor();
  check(await page.getByLabel('Исследование',{exact:true}).inputValue()==='cnrpark-day','Missing result prevented opening the project');
  await page.getByRole('button',{name:'Разметка',exact:true}).click();
  check(await page.locator('.slot-group').count()===54,'Missing result prevented repairing the layout');
  await page.unrouteAll({behavior:'wait'});
  await page.reload();
  await page.locator('.heatmap-layer[data-ready="true"]').waitFor();

  await page.getByRole('button',{name:'Новое видео',exact:true}).click();
  await page.getByLabel('Название',{exact:true}).fill('Длинное название исследования '.repeat(4).slice(0,100));
  await page.keyboard.press('Escape');
  check(await page.locator('dialog').count()===0,'Upload dialog does not close with Escape');
  await page.getByRole('button',{name:'Методика',exact:true}).click();
  check((await page.locator('main').innerText()).includes('30 минут'),'Sparse-source limitation is missing');
  await page.getByRole('button',{name:'Обзор',exact:true}).click();
  await page.getByLabel('Конец интервала',{exact:true}).fill('10800');
  await page.locator('.heatmap-layer[data-ready="true"]').waitFor();
  await page.getByLabel('Позиция видео',{exact:true}).fill('18');
  await page.waitForFunction(()=>!document.querySelector('video').seeking);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'artifacts/audit-after-desktop.png',fullPage:true});
  await page.locator('.video-column').screenshot({path:'artifacts/audit-after-map.png'});
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile page overflow');
  await page.screenshot({path:'artifacts/audit-after-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Весь день',exact:true}).click();
  await page.locator('.heatmap-layer[data-ready="true"]').waitFor();
  const final=await(await page.request.get(origin+'/api/projects/cnrpark-day')).json();
  check(final.revision===original.revision && final.latest_run.id===original.latest_run.id && JSON.stringify(final.slots)===JSON.stringify(original.slots),'The audit changed original analysis data');
  check(errors.length===0, errors.join('; '));
  return {passed:true,placement,stress:{observations:600,places:54,renderedCells:stressCells,unboundedCells:54*600},errors,scenarios:['period placement','navigation state','draft protection','undo cleanliness','retained draft','stale summary','summary retry','bounded matrix','cross-page keyboard seek','project request race','saved settings','missing result recovery','upload dialog','methodology','mobile','demo preservation']};
}
